/**
 * Renders the redirect table, the security headers and the cache rules for each place the site may be hosted (TRD §14, §15.2):
 * Apache, Nginx, static hosts that read `_redirects` and `_headers`, and, as a last resort for hosts that can do none of
 * these, HTML stubs at the old paths. Pure.
 */
import type { Redirect } from "@/content/redirects";
import { CACHE_IMMUTABLE, CACHE_PAGES, SECURITY_HEADERS } from "./security";

/** Both forms of an old path: with and without the trailing slash, since the old site had none and links vary. */
const variants = (from: string) => [from, `${from}/`];

const nonEmpty = (lines: string[]) => lines.join("\n") + "\n";

/**
 * Old paths that only gained a trailing slash (`/startups` → `/startups/`) need no rule: every web server already sends
 * `/startups` to `/startups/`, and a rule for them would loop.
 */
export const needsRule = (r: Redirect) => r.to !== `${r.from}/`;

/** Apache `.htaccess`: 301s, the 404 page, the security headers and caching (long for fingerprinted assets, short for pages). */
export function htaccess(all: readonly Redirect[]): string {
  const redirects = all.filter(needsRule);
  return nonEmpty([
    "# Generated by scripts/redirects.ts from src/content/redirects.ts and src/lib/security.ts. Do not edit.",
    "ErrorDocument 404 /404.html",
    "",
    "<IfModule mod_alias.c>",
    ...redirects.flatMap((r) =>
      variants(r.from).map(
        (from) => `  RedirectMatch 301 ^${from.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}$ "${r.to}"`,
      ),
    ),
    "</IfModule>",
    "",
    "<IfModule mod_headers.c>",
    ...SECURITY_HEADERS.map(([name, value]) => `  Header always set ${name} "${value}"`),
    '  <If "%{REQUEST_URI} =~ m#^/(_next/static|_img)/#">',
    `    Header set Cache-Control "${CACHE_IMMUTABLE}"`,
    "  </If>",
    '  <ElseIf "%{REQUEST_URI} =~ m#\\.html$|/$#">',
    `    Header set Cache-Control "${CACHE_PAGES}"`,
    "  </ElseIf>",
    "</IfModule>",
  ]);
}

/**
 * An Nginx snippet to include inside the `server` block. Nginx drops every inherited `add_header` in a block that sets
 * its own, so the security headers are repeated in each of the two caching locations.
 */
export function nginx(all: readonly Redirect[]): string {
  const redirects = all.filter(needsRule);
  const security = SECURITY_HEADERS.map(([name, value]) => `add_header ${name} "${value}" always;`);
  const location = (pattern: string, cache: string) => [
    `location ~ ${pattern} {`,
    ...security.map((line) => `  ${line}`),
    `  add_header Cache-Control "${cache}" always;`,
    "}",
  ];
  return nonEmpty([
    "# Generated by scripts/redirects.ts from src/content/redirects.ts and src/lib/security.ts. Do not edit.",
    "error_page 404 /404.html;",
    "",
    ...security,
    "",
    ...redirects.flatMap((r) =>
      variants(r.from).map((from) => `location = ${from} { return 301 ${r.to}; }`),
    ),
    "",
    ...location("^/(_next/static|_img)/", CACHE_IMMUTABLE),
    ...location("(\\.html|/)$", CACHE_PAGES),
  ]);
}

/** A `_headers` file for Cloudflare Pages and Netlify. */
export function headersFile(): string {
  return nonEmpty([
    "# Generated by scripts/redirects.ts from src/lib/security.ts. Do not edit.",
    "/*",
    ...SECURITY_HEADERS.map(([name, value]) => `  ${name}: ${value}`),
    "",
    "/_next/static/*",
    `  Cache-Control: ${CACHE_IMMUTABLE}`,
    "",
    "/_img/*",
    `  Cache-Control: ${CACHE_IMMUTABLE}`,
  ]);
}

/**
 * `vercel.json` for Vercel. Vercel reads it from the repository before it builds, so unlike the other files it is committed
 * rather than written into `public/`; `npm run redirects` rewrites it and tests/unit/vercel.test.ts keeps it honest.
 * The framework is `null` ("Other"), not `nextjs`: with the Next.js preset Vercel's builder looks for `routes-manifest.json`
 * in the output directory and fails on a static export, which has none. As a plain static site it just serves `out/`.
 */
export function vercelConfig(all: readonly Redirect[]) {
  const header = (source: string, headers: readonly (readonly [string, string])[]) => ({
    source,
    headers: headers.map(([key, value]) => ({ key, value })),
  });
  return {
    $schema: "https://openapi.vercel.sh/vercel.json",
    framework: null,
    installCommand: "npm ci",
    buildCommand: "npm run build",
    outputDirectory: "out",
    trailingSlash: true,
    cleanUrls: false,
    redirects: all
      .filter(needsRule)
      .flatMap((r) =>
        variants(r.from).map((source) => ({ source, destination: r.to, permanent: true })),
      ),
    headers: [
      header("/(.*)", SECURITY_HEADERS),
      header("/_next/static/(.*)", [["Cache-Control", CACHE_IMMUTABLE]]),
      header("/_img/(.*)", [["Cache-Control", CACHE_IMMUTABLE]]),
    ],
  };
}

/** A `_redirects` file for Cloudflare Pages and Netlify. */
export function redirectsFile(all: readonly Redirect[]): string {
  const redirects = all.filter(needsRule);
  return nonEmpty([
    "# Generated by scripts/redirects.ts from src/content/redirects.ts. Do not edit.",
    ...redirects.flatMap((r) => variants(r.from).map((from) => `${from} ${r.to} 301`)),
  ]);
}

const escapeHtml = (text: string) =>
  text.replace(
    /[&<>"]/g,
    (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c] as string,
  );

/**
 * The page at an old path for a host that cannot redirect: an instant meta refresh, a canonical link and a visible link, so
 * it works without script and tells a person where they are going.
 */
export function stubHtml(redirect: Redirect, site: { url: string; name: string }): string {
  const target = `${site.url}${redirect.to}`;
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>This page has moved · ${escapeHtml(site.name)}</title>
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="robots" content="noindex">
<link rel="canonical" href="${escapeHtml(target)}">
<meta http-equiv="refresh" content="0; url=${escapeHtml(redirect.to)}">
</head>
<body>
<p>This page has moved. <a href="${escapeHtml(redirect.to)}">Go to the new page</a>.</p>
</body>
</html>
`;
}
