/**
 * Security headers and the Content-Security-Policy (TRD §14, NFR-SEC). Pure, so tests/unit/security.test.ts can check every
 * rule; scripts/csp.ts applies it to the built pages and scripts/headers.ts writes the host files.
 *
 * Why the policy is a `<meta>` tag on each page rather than one header: Next puts inline scripts in every page (the theme
 * script, the runtime bootstrap, and a payload that differs from page to page), and a CSP can only allow an inline script
 * by its hash. One header for the whole site cannot list them all, so each page carries its own policy with its own hashes.
 * A policy in a `<meta>` cannot set `frame-ancestors`, so that one directive, and the other security headers, go in the
 * host configuration generated by scripts/headers.ts.
 */
import { createHash } from "node:crypto";
import { endpointOrigins, originOf } from "./origins";

export { endpointOrigins, originOf };

export interface PolicyInput {
  /** Hashes of the page's inline scripts, as `sha256-…` (see `inlineScriptHashes`). */
  scriptHashes: readonly string[];
  /** Origins the page may script from besides itself (an analytics script). */
  scriptOrigins?: readonly string[];
  /** Origins `fetch` may talk to besides the site: the form endpoint, an analytics host. */
  connectOrigins?: readonly string[];
  /** Origins the page may embed: the map. The click-to-load video host is always allowed. */
  frameOrigins?: readonly string[];
  /** Origins a plain HTML form may post to besides the site (the form endpoint, with JavaScript off). */
  formOrigins?: readonly string[];
}

/** Video loads only after a click, and only from YouTube's privacy-enhanced host (SPEC §4.4, TRD §14). */
export const VIDEO_ORIGIN = "https://www.youtube-nocookie.com";

const unique = (values: readonly string[]) => [...new Set(values)];

/** The policy for one page. Everything not listed is blocked: `default-src 'self'` is the floor. */
export function buildPolicy(input: PolicyInput): string {
  const hashes = input.scriptHashes.map((h) => `'${h}'`);
  const directives: [string, string[]][] = [
    ["default-src", ["'self'"]],
    ["script-src", unique(["'self'", ...hashes, ...(input.scriptOrigins ?? [])])],
    ["style-src", ["'self'"]],
    // React writes `style="…"` for a few computed values (an image's aspect ratio, the spinbar's transforms); attributes only.
    ["style-src-attr", ["'unsafe-inline'"]],
    ["img-src", ["'self'", "data:"]],
    ["font-src", ["'self'"]],
    ["connect-src", unique(["'self'", ...(input.connectOrigins ?? [])])],
    ["frame-src", unique([VIDEO_ORIGIN, ...(input.frameOrigins ?? [])])],
    ["form-action", unique(["'self'", ...(input.formOrigins ?? [])])],
    ["base-uri", ["'self'"]],
    ["object-src", ["'none'"]],
    ["manifest-src", ["'self'"]],
  ];
  return directives.map(([name, values]) => `${name} ${values.join(" ")}`).join("; ");
}

/** Types whose content the browser never runs, so the policy has nothing to say about them (JSON-LD, JSON data). */
const DATA_TYPE = /\stype\s*=\s*["']?(application\/(ld\+)?json|text\/plain)["']?/i;

/** `sha256-…` of the exact text of every inline script that the browser would run, in page order, without duplicates. */
export function inlineScriptHashes(html: string): string[] {
  const hashes: string[] = [];
  for (const [, attrs = "", body = ""] of html.matchAll(
    /<script\b([^>]*)>([\s\S]*?)<\/script>/gi,
  )) {
    if (/\ssrc\s*=/i.test(attrs) || DATA_TYPE.test(attrs)) continue;
    hashes.push(`sha256-${createHash("sha256").update(body, "utf8").digest("base64")}`);
  }
  return unique(hashes);
}

const META = /<meta\s+http-equiv=["']content-security-policy["'][^>]*>/i;

/**
 * Puts the policy in the page's `<head>`, directly after the charset, so it governs everything that follows. A page that
 * already has one has it replaced, so the step can be run twice. Returns the page unchanged if it has no `<head>`.
 */
export function injectPolicy(html: string, policy: string): string {
  const tag = `<meta http-equiv="content-security-policy" content="${policy.replace(/"/g, "&quot;")}"/>`;
  const cleaned = html.replace(META, "");
  const charset = /<meta\s+charset=["']?[\w-]+["']?\s*\/?>/i.exec(cleaned);
  if (charset)
    return `${cleaned.slice(0, charset.index + charset[0].length)}${tag}${cleaned.slice(charset.index + charset[0].length)}`;
  const head = /<head[^>]*>/i.exec(cleaned);
  if (!head) return html;
  return `${cleaned.slice(0, head.index + head[0].length)}${tag}${cleaned.slice(head.index + head[0].length)}`;
}

